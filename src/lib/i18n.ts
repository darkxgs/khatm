export const dict = (l: Lang): Dict => (l === "ar" ? ar : en);

/** The month's name, for "Received in October". */
export function monthName(day: string, l: Lang): string {
  return new Intl.DateTimeFormat(l === "ar" ? "ar-SA-u-ca-gregory-nu-latn" : "en-GB", { month: "long", timeZone: "UTC" }).format(new Date(`${day.slice(0, 7)}-15T00:00:00Z`));
}
